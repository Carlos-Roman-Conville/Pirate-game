"""Reachability table for the town endings (opportunity, not chance).

Reads maps.json next to this file and writes TABLE.md next to it (also prints it).
Run: python reach.py

A character "can reach" a quadrant if some witnessed action moves them there, if a
'stay' cell holds them at a known start there, or if they start there.
  yes    = follows from Rex's decided maps/starts
  map?   = only possible through a map cell that is still open (or a map not made)
  start? = the map is complete and never lands there; only an open starting
           alignment there (kept by never pushing them) would reach it
  no     = ruled out (Rex's 'never', or map and start both settled elsewhere)
A sector covers an ending if at least one of its pair can reach it.
Routes per ending = one character per sector who can reach it, multiplied out.
"""
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
NAMES = {"og": "Orderly good", "cg": "Chaotic good", "oe": "Orderly evil", "ce": "Chaotic evil"}


def reach(char, quads):
    m, start, never = char["map"], char["start"], set(char["never"])
    map_open = any(v is None for v in m.values())
    yes = {v for v in m.values() if v in quads}
    if start in quads:
        yes.add(start)
    out = {}
    for q in quads:
        if q in never:
            out[q] = "no"
        elif q in yes:
            out[q] = "yes"
        else:
            out[q] = "map?" if map_open else ("start?" if start is None else "no")
    return out


def main():
    data = json.loads((HERE / "maps.json").read_text(encoding="utf-8"))
    quads = data["quadrants"]
    chars = data["characters"]
    r = {slug: reach(c, quads) for slug, c in chars.items()}
    lines = ["# Reachability (generated by reach.py from maps.json; do not edit by hand)", ""]

    lines += ["## Per character", "", "| Character | " + " | ".join(q.upper() for q in quads) + " | Source |",
              "|---|" + "---|" * len(quads) + "---|"]
    for slug in chars:
        lines.append(f"| `{slug}` | " + " | ".join(r[slug][q] for q in quads) + f" | {chars[slug]['mark']} |")

    lines += ["", "## Per sector (a sector covers an ending if either of its pair can reach it)", "",
              "| Sector | Pair | Mark | " + " | ".join(q.upper() for q in quads) + " |",
              "|---|---|---|" + "---|" * len(quads)]
    cover = {}
    for s in data["sectors"]:
        cells = []
        for q in quads:
            who_yes = [c for c in s["pair"] if r[c][q] == "yes"]
            who_maybe = [c for c in s["pair"] if r[c][q] in ("map?", "start?")]
            tag = lambda cs: ", ".join(f"{c} ({r[c][q]})" for c in cs)
            if who_yes:
                v, cell = "yes", "yes: " + ", ".join(who_yes) + (" (+ " + tag(who_maybe) + ")" if who_maybe else "")
            elif who_maybe:
                v, cell = "maybe", "**open only: " + tag(who_maybe) + "**"
            else:
                v, cell = "no", "**STARVED**"
            cover[(s["id"], q)] = (v, len(who_yes), len(who_maybe))
            cells.append(cell)
        lines.append(f"| {s['name']} | {' / '.join(s['pair'])} | {s['mark']} | " + " | ".join(cells) + " |")

    lines += ["", "## Per ending", "",
              "| Ending | Characters who can reach it (yes) | Could, through something open | Sectors covered now | Sectors resting only on something open | Starved sectors | Routes now | Routes if open maps allow |",
              "|---|---|---|---|---|---|---|---|"]
    for q in quads:
        ys = [c for c in chars if r[c][q] == "yes"]
        ms = [f"{c} ({r[c][q]})" for c in chars if r[c][q] in ("map?", "start?")]
        covered = [s["name"] for s in data["sectors"] if cover[(s["id"], q)][0] == "yes"]
        only_open = [s["name"] for s in data["sectors"] if cover[(s["id"], q)][0] == "maybe"]
        starved = [s["name"] for s in data["sectors"] if cover[(s["id"], q)][0] == "no"]
        now, best = 1, 1
        for s in data["sectors"]:
            _, ny, nm = cover[(s["id"], q)]
            now *= ny
            best *= ny + nm
        lines.append(f"| {NAMES[q]} | {', '.join(ys) or '-'} ({len(ys)}) | {', '.join(ms) or '-'} | "
                     f"{len(covered)}/{len(data['sectors'])} | {', '.join(only_open) or '-'} | {', '.join(starved) or '-'} | {now} | {best} |")

    text = "\n".join(lines) + "\n"
    (HERE / "TABLE.md").write_text(text, encoding="utf-8")
    print(text)


if __name__ == "__main__":
    main()
