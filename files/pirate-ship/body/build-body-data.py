#!/usr/bin/env python3
"""Body and world data build (body-and-world keeper, 2026-10-29).

One source of truth: the JSON files in body/data/. This script

1. renders every table into the docs between `<!-- table:<file>.<key> -->` and `<!-- /table -->`
   markers (body/*.md and world/*.md), so a doc never disagrees with its data;
2. writes body/data.js (`window.BODY_DATA = {...}`) for body/dashboard.html, which opens from the
   file system with no server (a static page cannot fetch JSON over file://).

Run from anywhere:  python files/pirate-ship/body/build-body-data.py
Never edit a rendered table by hand; edit the JSON and rerun.
"""
import json, re, sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
DATA = HERE / "data"
DOCS = list(HERE.glob("*.md")) + list((HERE.parent / "world").glob("*.md"))
MARK = {"rex": "**Rex**", "proposed": "proposed", "open": "**open**", "outside": "proposed (outside AI)", "science": "science", "history": "history", "model": "model", "fiction": "fiction"}


def load():
    out = {}
    for p in sorted(DATA.glob("*.json")):
        with p.open(encoding="utf-8") as f:
            out[p.stem] = json.load(f)
    return out


def cell(v):
    if v is None:
        return "open"
    if isinstance(v, bool):
        return "yes" if v else "no"
    if isinstance(v, float):
        s = f"{v:.3f}".rstrip("0").rstrip(".")
        return s
    if isinstance(v, list):
        return ", ".join(cell(x) for x in v)
    if isinstance(v, dict):
        return "; ".join(f"{k} {cell(x)}" for k, x in v.items())
    s = str(v)
    return s.replace("|", "\\|").replace("\n", " ")


def render(table):
    cols = table["columns"]
    lines = []
    head = f"*{table.get('title','')}* ({table.get('kind','model')}; confidence {table.get('conf','medium')}; source: {table.get('source','')})"
    lines.append(head)
    lines.append("")
    lines.append("| " + " | ".join(cols) + " |")
    lines.append("|" + "---|" * len(cols))
    for row in table["rows"]:
        if isinstance(row, dict):
            row = [row.get(c) for c in table.get("keys", cols)]
        r = [cell(x) for x in row]
        if r and r[-1] in MARK and cols[-1].lower() == "mark":
            r[-1] = MARK[r[-1]]
        lines.append("| " + " | ".join(r) + " |")
    return "\n".join(lines)


PAT = re.compile(r"(<!-- table:([a-z_]+)\.([a-z_]+) -->)\n.*?(<!-- /table -->)", re.S)


def render_docs(data):
    changed = 0
    for doc in DOCS:
        text = doc.read_text(encoding="utf-8")

        def sub(m):
            f, k = m.group(2), m.group(3)
            if f not in data or k not in data[f]:
                print(f"  {doc.name}: no table {f}.{k}", file=sys.stderr)
                return m.group(0)
            return f"{m.group(1)}\n{render(data[f][k])}\n{m.group(4)}"

        new = PAT.sub(sub, text)
        if new != text:
            doc.write_text(new, encoding="utf-8")
            changed += 1
    return changed


def write_js(data):
    js = "// Generated by build-body-data.py from body/data/*.json. Do not edit.\nwindow.BODY_DATA = " + json.dumps(data, ensure_ascii=False, indent=1) + ";\n"
    (HERE / "data.js").write_text(js, encoding="utf-8")


if __name__ == "__main__":
    data = load()
    n = render_docs(data)
    write_js(data)
    print(f"{len(data)} data files; {n} docs re-rendered; data.js written")
